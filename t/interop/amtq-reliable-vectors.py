#!/usr/bin/env python3
"""Print stable AMTQ wire fixtures using the pinned independent Rust codecs.
Usage: python3 t/interop/amtq-reliable-vectors.py /path/to/QUICast-amt
Requires rustc; no Cargo dependencies or network access are needed.
"""
import pathlib
import struct
import subprocess
import sys
import tempfile

REFERENCE_COMMIT = "cdfb1d58602dc73ee196a1d019da10dec35f3b51"
REFERENCE_FILES = ["crates/quicast-amtq/src/" + name + ".rs" for name in ("error", "varint", "reliable", "control")]

RUST = r'''
#![allow(dead_code)]
#[path = "@REFERENCE@/crates/quicast-amtq/src/error.rs"] mod error;
#[path = "@REFERENCE@/crates/quicast-amtq/src/varint.rs"] mod varint;
#[path = "@REFERENCE@/crates/quicast-amtq/src/reliable.rs"] mod reliable;
#[path = "@REFERENCE@/crates/quicast-amtq/src/control.rs"] mod control;
pub use error::WireError;
pub const MAX_CONTROL_RECORD_VALUE: usize = 65587;
pub const MAX_AMT_DATA_MESSAGE: usize = 65577;
#[derive(Debug, Clone, Copy, PartialEq, Eq)] pub enum EndpointRole { Gateway, Relay }
fn emit(name: &str, bytes: &[u8]) {
    print!("static const uint8_t {}[] = {{", name);
    for (i, b) in bytes.iter().enumerate() { if i % 12 == 0 { print!("\n  "); } print!("0x{:02x}, ", b); }
    println!("\n}};");
}
fn main() {
    let message = std::fs::read(std::env::args().nth(1).unwrap()).unwrap();
    emit("golden_message", &message);
    let mut out=Vec::new();
    control::ControlRecord::Settings(control::Settings::gateway(3,Some(1))).encode(EndpointRole::Gateway,&mut out).unwrap();
    emit("golden_gateway_settings", &out); out.clear();
    control::ControlRecord::Settings(control::Settings{data_modes:3,preferred_data_mode:None}).encode(EndpointRole::Relay,&mut out).unwrap();
    emit("golden_relay_settings", &out); out.clear();
    control::ControlRecord::Context(control::Context{id:64,mode:1}).encode(EndpointRole::Relay,&mut out).unwrap();
    emit("golden_context", &out); out.clear();
    reliable::encode_stream_header(64,64,&mut out).unwrap(); emit("golden_header", &out); out.clear();
    reliable::encode_data_record(&message,&mut out).unwrap(); emit("golden_record", &out); out.clear();
    control::ControlRecord::ContextClose(control::ContextClose{id:64,final_block_id:Some(64)}).encode(EndpointRole::Relay,&mut out).unwrap();
    emit("golden_close", &out);
}
'''

reference = pathlib.Path(sys.argv[1]).resolve()
try:
    head = subprocess.check_output(["git", "-C", str(reference), "rev-parse", "--verify", "HEAD"], text=True).strip()
except subprocess.CalledProcessError as error:
    raise SystemExit("reference must be a Git checkout of " + REFERENCE_COMMIT) from error
if head != REFERENCE_COMMIT:
    raise SystemExit("reference HEAD is " + head + "; expected " + REFERENCE_COMMIT)
if subprocess.run(["git", "-C", str(reference), "diff", "--quiet", "--no-ext-diff", "HEAD", "--", *REFERENCE_FILES]).returncode:
    raise SystemExit("reference codec files must be unmodified at " + REFERENCE_COMMIT)
with tempfile.TemporaryDirectory(prefix="nanoamt-reliable-vectors-") as directory:
    work = pathlib.Path(directory)
    # Independently constructed IPv4 UDP packet: 192.0.2.10 -> 232.1.2.3:5000.
    ip = bytearray.fromhex("450000211234000010110000c000020ae8010203")
    total = sum(struct.unpack("!10H", ip))
    total = (total & 65535) + (total >> 16)
    ip[10:12] = struct.pack("!H", 65535 - total)
    message = b"\6\0" + ip + struct.pack("!4H", 1234, 5000, 13, 0) + b"hello"
    (work / "message").write_bytes(message)
    (work / "generate.rs").write_text(RUST.replace("@REFERENCE@", str(reference)))
    subprocess.run(["rustc", "--edition=2024", str(work / "generate.rs"), "-o", str(work / "generate")], check=True)
    print("/* Generated by t/interop/amtq-reliable-vectors.py using unmodified QUICast AMT")
    print(" * reliable.rs/control.rs/varint.rs at " + REFERENCE_COMMIT + ".")
    print(" * Static wire vectors intentionally do not use nanoamt codecs. */", flush=True)
    subprocess.run([str(work / "generate"), str(work / "message")], check=True)
